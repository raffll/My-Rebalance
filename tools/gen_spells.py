#!/usr/bin/env python3
"""Generate the buyable spell lists for R3 - Spells Lua and R3 - Rounding Lua.

A spell is buyable when a spell merchant (NPC offering spells) in the full TR
load order knows it and its type is Spell (see find_buyable_spells.py).
Writes the same lowercase id list to:
- scripts/R3SpellsLua/spells.lua
- scripts/R3RoundingLua/spells.lua

The R3 base costs are not generated: they live in scripts/R3SpellsLua/costs.lua.

Usage:
  python tools/gen_spells.py
"""
from __future__ import annotations
import json
import os
import sys

MOD_DIR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import find_buyable_spells as fbs  # noqa: E402

OUTPUTS = [
    os.path.join(MOD_DIR, "scripts", "R3SpellsLua", "spells.lua"),
    os.path.join(MOD_DIR, "scripts", "R3RoundingLua", "spells.lua"),
]


def main() -> int:
    spells_by_id, npcs = fbs.build_data(fbs.LOAD_ORDER)
    _, buyable = fbs.collect(spells_by_id, npcs, tr_only=False)
    ids = sorted(buyable)
    for out in OUTPUTS:
        os.makedirs(os.path.dirname(out), exist_ok=True)
        with open(out, "w", encoding="utf-8", newline="\n") as f:
            f.write("-- Generated by tools/gen_spells.py. Do not edit.\n")
            f.write("-- Buyable spell ids (lowercase).\nreturn {\n")
            for i in ids:
                f.write(f"    {json.dumps(i)},\n")
            f.write("}\n")
        print(f"{out}: {len(ids)} spells")
    return 0


if __name__ == "__main__":
    sys.exit(main())
